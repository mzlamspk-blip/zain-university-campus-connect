def check(label, response, expected):
    actual = response.status_code
    print(f"{'OK ' if actual == expected else 'FAIL'} {label}: {actual}")
    if actual != expected:
        raise SystemExit(1)


def student_id_for(user):
    doc = db["students"].find_one({"username": user})
    return str(doc["_id"])


